"""The Stop hook looks for an area's node_modules in the area's own folder (desktop/, worker/, site/), not only at the repo root."""
# 11 Oct 2026: every worktree session was told "desktop not tested: no node_modules", so the Stop hook never ran their suites.
import unittest
from pathlib import Path

HOOK = (Path(__file__).resolve().parent.parent / 'tools' / 'stop-test-check.sh').read_text()


class StopHookNodeModulesTest(unittest.TestCase):
    def test_the_check_looks_in_the_areas_own_folder(self):
        self.assertIn('[ ! -e "$repo/$s/node_modules" ]', HOOK, 'a worktree whose desktop/node_modules exists must not be reported "not tested"')


if __name__ == '__main__':
    unittest.main()
