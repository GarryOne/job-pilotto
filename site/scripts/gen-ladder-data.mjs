// Builds src/applying-ladder-data.js, the AI ladder card's table, FROM THE CODE: each rung's files, the first sentence of each file's header comment and the model and price it exports.
// Only the rung's name, cost kind and file list are written here; test/applying-ladder.test.js fails when the data file is stale, a listed file is missing or a rung* file is not listed.
// Run `node site/scripts/gen-ladder-data.mjs` after changing a rung file's header, model or price.
import {readFileSync, readdirSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

const ROOT = fileURLToPath(new URL('../../', import.meta.url));
const DATA = fileURLToPath(new URL('../src/applying-ladder-data.js', import.meta.url));
export const LADDER_DIRS = ['desktop/lib/ladder', 'extension/ladder'];
export const FILL_FILES = ['extension/ladder/fill-climb.js', 'extension/ladder/fill-repair.js', 'desktop/lib/ladder/fill-repair.js', 'desktop/lib/ladder/fill-verify.js'];   // the same ladder, climbed for a field's value
// kind: free | tokens | agent | person. Files that do not exist on purpose (rung 6, the card) are named in `where`.
export const RUNGS = [
  {n: 0, name: 'Structure rule', kind: 'free', files: ['extension/tab-pages.js']},
  {n: 1, name: 'Kept answer per page shape', kind: 'free', files: ['desktop/lib/ladder/rung1-kept.js']},
  {n: 2, name: 'Text sketch to the small model', kind: 'tokens', files: ['desktop/lib/ladder/rung2-sketch.js']},
  {n: 3, name: 'Numbered digest to the small model', kind: 'tokens', files: ['desktop/lib/ladder/rung3-digest.js', 'extension/ladder/rung3-candidates.js', 'extension/ladder/rung3-frames.js']},
  {n: 4, name: 'Screenshot plus sketch, one action', kind: 'tokens', files: ['desktop/lib/ladder/rung4-picture.js', 'extension/ladder/rung4-picture.js', 'extension/ladder/rung4-page-picture.js']},
  {n: 5, name: 'Claude takes over the page', kind: 'agent', files: ['desktop/lib/ladder/rung5-takeover.js', 'desktop/lib/ladder/rung5-takeover-teach.js']},
  {n: 6, name: 'The person, with the page\'s sentence quoted', kind: 'person', files: [], where: 'the session card'}];

const read = file => readFileSync(ROOT + file, 'utf8');
// First sentence of the file's leading // comment block, trimmed to a short line.
function headline(text) {
  const block = [];
  for (const line of text.split('\n')) { if (!line.startsWith('//')) break; block.push(line.replace(/^\/\/\s?/, '')); }
  const sentence = block.join(' ').replace(/\s+/g, ' ').trim().split(/(?<=[a-z)]\.)\s/)[0] || '';
  return sentence.length > 200 ? sentence.slice(0, 197).replace(/\s\S*$/, '') + '...' : sentence;
}
function modelOf(text) {
  const literal = text.match(/export const MODEL = '([\w.-]+)'/)?.[1], tier = text.match(/export const MODEL = model\('(\w+)'\)/)?.[1];
  const price = text.match(/const PRICE = \{input: ([\d.]+), output: ([\d.]+)\}/);
  return {model: literal || (tier ? tier + ' tier' : null), price: price ? {input: Number(price[1]), output: Number(price[2])} : null};
}
export function build() {
  const rungs = RUNGS.map(({n, name, kind, files, where}) => {
    const found = files.map(file => ({file, about: headline(read(file)), ...modelOf(read(file))}));
    const withModel = found.find(item => item.model);
    return {n, name, kind, where: where || null, model: withModel?.model || null, price: withModel?.price || null, files: found.map(({file, about}) => ({file, about}))};
  });
  const fills = FILL_FILES.map(file => ({file, about: headline(read(file))}));
  return {rungs, fills};
}
export const listedFiles = () => new Set([...RUNGS.flatMap(rung => rung.files), ...FILL_FILES]);
export const rungFilesOnDisk = () => LADDER_DIRS.flatMap(dir => readdirSync(ROOT + dir).filter(name => name.startsWith('rung')).map(name => dir + '/' + name));
export const render = () => '// GENERATED by site/scripts/gen-ladder-data.mjs from the rung files\' own header comments, MODEL and PRICE; do not edit by hand (test/applying-ladder.test.js fails when it is stale).\nexport const LADDER_DATA = ' + JSON.stringify(build(), null, 1) + ';\n';
if (process.argv[1] === fileURLToPath(import.meta.url)) { writeFileSync(DATA, render()); console.log('wrote ' + DATA); }
